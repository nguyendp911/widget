import Foundation

let storeDefaults = UserDefaults(suiteName: "viepn.utility-smoke.\(UUID().uuidString)")!
let repo = UtilityRepository(defaults: storeDefaults)
assert(repo.addExpense(amount: 20_000, category: .food))
assert(repo.addExpense(amount: 50_000, category: .travel))
assert(repo.load().spentThisMonth() == 70_000)
assert(repo.load().remainingBudget() == 2_930_000)
assert(!repo.addExpense(amount: -1))
assert(repo.addTask("Đi siêu thị"))
let task = repo.load().tasks[0]
repo.toggleTask(task.id)
assert(repo.load().pendingTasks.count == 0)
repo.toggleTask(task.id)
assert(repo.load().pendingTasks.count == 1)
assert(repo.addBill(name: "Internet", amount: 220_000, dueDay: 20))
let bill = repo.load().bills[0]
repo.toggleBillPaid(bill.id)
assert(repo.load().nextUnpaidBill() == nil)
repo.toggleBillPaid(bill.id)
assert(repo.load().nextUnpaidBill() != nil)
assert(repo.addNote("Một ý tưởng hay"))
repo.setRevealOnWidgets(false)
assert(!repo.load().revealOnWidgets)
assert(repo.load().latestNote?.text == "Một ý tưởng hay")
let now = Date()
repo.toggleFocus(minutes: 25, now: now)
assert(repo.load().activeFocus(at: now) != nil)
assert(repo.load().activeFocus(at: now.addingTimeInterval(26*60)) == nil)
repo.toggleFocus(minutes: 25, now: now)
assert(repo.load().focusSession == nil)
print("UTILITY TESTS PASS: expense, budget, task toggle, bills, notes, privacy, focus")
